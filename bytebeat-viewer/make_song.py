#!/usr/bin/env python3
"""Generate song.h (the bytebeat compiled into the app).

Usage:
  python3 make_song.py "https://dollchan.net/bytebeat/#v3b64..."   # a dollchan share link
  python3 make_song.py --code "t*(t>>5|t>>8)" [--rate 8000] [--mode Bytebeat] [--title "name"]

Modes: Bytebeat, "Signed Bytebeat", Floatbeat, Funcbeat
"""
import argparse, base64, json, struct, sys, zlib

MODES = ["Bytebeat", "Signed Bytebeat", "Floatbeat", "Funcbeat"]


def inflate(data: bytes) -> bytes:
    for wbits in (-15, 15, 31):
        try:
            return zlib.decompress(data, wbits)
        except zlib.error:
            pass
    raise ValueError("could not decompress link data")


def b64(s: str) -> bytes:
    s = s.strip()
    return base64.b64decode(s + "=" * (-len(s) % 4))


def parse_link(url: str) -> dict:
    h = url[url.index("#"):] if "#" in url else url
    if h.startswith("#v3b64"):
        txt = inflate(b64(h[6:])).decode("utf-8")
        if txt.startswith("{"):
            d = json.loads(txt)
            if d.get("formula"):
                d["code"] = d["formula"]
            return d
        return {"code": txt}
    if h.startswith("#4"):
        raw = b64(h[2:])
        return {"mode": MODES[raw[0]], "sampleRate": struct.unpack("<f", raw[1:5])[0],
                "code": inflate(raw[5:]).decode("utf-8")}
    raise ValueError("unrecognised dollchan link (expected #v3b64... or #4...)")


def c_string(s: str) -> str:
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c == "\\": out.append("\\\\")
        elif c == '"': out.append('\\"')
        elif c == "\n": out.append('\\n"\n"')
        elif c == "\r": continue
        elif c == "\t": out.append("\\t")
        elif 32 <= ch < 127 and c != "?": out.append(c)
        else: out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("link", nargs="?")
    ap.add_argument("--code")
    ap.add_argument("--rate", type=float)
    ap.add_argument("--mode")
    ap.add_argument("--title")
    ap.add_argument("-o", "--out", default="song.h")
    a = ap.parse_args()

    d = parse_link(a.link) if a.link else {}
    if a.code is not None: d["code"] = a.code
    if a.rate: d["sampleRate"] = a.rate
    if a.mode: d["mode"] = a.mode
    if "code" not in d:
        sys.exit("need a dollchan link or --code")
    mode = d.get("mode") or "Bytebeat"
    if mode not in MODES:
        sys.exit(f"unknown mode {mode!r}")
    rate = float(d.get("sampleRate") or 8000)
    title = a.title or "Bytebeat"

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("// Generated by make_song.py\n#pragma once\n")
        f.write(f"#define SONG_TITLE {c_string(title)}\n")
        f.write(f"#define SONG_MODE {MODES.index(mode)} // {mode}\n")
        f.write(f"#define SONG_RATE {rate!r}\n")
        f.write(f"static const char SONG_CODE[] =\n{c_string(d['code'])};\n")
    print(f"wrote {a.out}: mode={mode} rate={rate} code={len(d['code'])} chars")


if __name__ == "__main__":
    main()
